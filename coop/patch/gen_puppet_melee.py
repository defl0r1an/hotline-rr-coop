"""Generates coop/gml/gml_Script_scrCoopPuppetAttack.gml and ..._scrCoopPuppetPunch.gml from the game's own
melee scripts (decompiled/CodeEntries), so the host can resolve the partner's melee swings as the puppet.

Transform:
  * objPlayer (the player group) -> objCoopPuppet: hit tests, directions and weapon checks use the puppet.
  * with (objPlayerMouse) / with (objPlayerBiker) -> with (objCoopPuppet): the execution branches that destroy
    the attacker's body destroy the puppet instead (it is re-created by the next PSTATE).
  * instance_create(..., objBikerKillFat / objPKillChainsawFat / objPKillDog) -> objCoopMarker: those kill
    animations are objPlayer children and would add a second player body on the host.
Run:  python -I coop/patch/gen_puppet_melee.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "decompiled" / "CodeEntries"
OUT = ROOT / "coop" / "gml"
KILL_ANIMS = ("objBikerKillFat", "objPKillChainsawFat", "objPKillDog")

JOBS = {
    "scrPlayerIsAttacking": "scrCoopPuppetAttack",
    "scrPlayerIsPunching": "scrCoopPuppetPunch",
}

for src_name, dst_name in JOBS.items():
    text = (SRC / f"gml_Script_{src_name}.gml").read_text(encoding="utf-8")
    text = re.sub(r"\bobjPlayer\b", "objCoopPuppet", text)
    text = re.sub(r"with \((objPlayerMouse|objPlayerBiker)\)", "with (objCoopPuppet)", text)
    for anim in KILL_ANIMS:
        text = re.sub(rf"(instance_create\([^;]*?,\s*){anim}\)", r"\1objCoopMarker)", text)
    header = (
        f"// GENERATED by coop/patch/gen_puppet_melee.py from {src_name} - do not edit by hand.\n"
        "// Host only: the partner's melee swing resolved as objCoopPuppet (see objCoopPuppet Step).\n"
    )
    (OUT / f"gml_Script_{dst_name}.gml").write_text(header + text, encoding="utf-8")
    left = sorted(set(re.findall(r"\bobjP[A-Za-z0-9_]*", text)))
    print(dst_name, "lines:", text.count("\n"), "remaining objP* names:", left)
